export interface Input {
  /**
   * Exact name of the vault to delete. The caller must own this vault and hold admin scope on it.
   */
  vault: string;
}

export type Output =
  | {
      /**
       * True when the vault was deleted; false on auth/scope/ownership error.
       */
      ok: boolean;
      /**
       * The deleted vault name. Present when ok is true.
       */
      vault?: string;
      /**
       * Number of notes removed from the vault. Present when ok is true.
       */
      deletedNotes?: number;
      /**
       * Number of facts (active + superseded) removed from the vault. Present when ok is true.
       */
      deletedFacts?: number;
      /**
       * Human-readable failure reason when ok is false.
       */
      error?: string;
    }
  | {
      delivery: {
        mode: "artifact";
        status: "complete" | "partial" | "unavailable";
        retainedRepresentation: "formatted-tool-result";
        sourceIsError: boolean;
        artifacts: {
          artifactId: string;
          filename: string;
          contentType: string;
          bytes: number;
          sha256: string;
          expiresAt: string;
          capabilities: string[];
          downloadUrl: string | null;
          downloadUrlExpiresAt: string | null;
          downloadState: "available" | "local" | "unavailable";
        }[];
        availableExports?: {
          artifactId: string;
          sourceArtifactId: string;
          filename: "result.md";
          contentType: "text/markdown; charset=utf-8";
          state: "on-demand";
        }[];
        downloadLinksOmitted: boolean;
        scopeOmittedFields: number;
        storageFailure: {
          artifactId: string | null;
          outcome: "unknown" | "bytes-stored-metadata-pending" | "failed";
        } | null;
        nextAction: string;
      };
      preview: string;
      scope: {
        [k: string]: string | number | boolean | null;
      };
      recovery: {
        idempotencyKey?: string;
        operationId?: string;
        runId?: string;
        jobId?: string;
        operation?: {
          runId: string | null;
          idempotencyKey: string;
          state: string;
        };
      };
    };
