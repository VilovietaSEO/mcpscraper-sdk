    plus_code: Any | None = Field(None, alias="plusCode", description="")
    booking_url: Any | None = Field(None, alias="bookingUrl", description="")
    kgmid: Any | None = Field(None, alias="kgmid", description="")
    cid_decimal: Any | None = Field(None, alias="cidDecimal", description="")
