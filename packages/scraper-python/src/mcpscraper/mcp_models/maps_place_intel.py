    unavailable_fields: list[str] | None = Field(None, alias="unavailableFields", description="")
    requested_max_reviews: int | None = Field(None, alias="requestedMaxReviews", description="")
    requested_max_images: int | None = Field(None, alias="requestedMaxImages", description="")
    images_collected: int | None = Field(None, alias="imagesCollected", description="")
    billing_state: str | None = Field(None, alias="billingState", description="")
    status_path: str | None = Field(None, alias="statusPath", description="")
    reviews_next_cursor: Any | None = Field(None, alias="reviewsNextCursor", description="")
    images_next_cursor: Any | None = Field(None, alias="imagesNextCursor", description="")
    maximum_authorization_mc: int | None = Field(None, alias="maximumAuthorizationMc", description="")
    provider: str | None = Field(None, alias="provider", description="")
    fallback_from: str | None = Field(None, alias="fallbackFrom", description="")
    acquisition_provider: str | None = Field(None, alias="acquisitionProvider", description="")
    name: Any | None = Field(None, alias="name", description="")
    place_url: Any | None = Field(None, alias="placeUrl", description="")
    rating: Any | None = Field(None, alias="rating", description="")
    review_count: Any | None = Field(None, alias="reviewCount", description="")
    category: Any | None = Field(None, alias="category", description="")
    address: Any | None = Field(None, alias="address", description="")
    phone: Any | None = Field(None, alias="phone", description="")
    website: Any | None = Field(None, alias="website", description="")
    hours_summary: Any | None = Field(None, alias="hoursSummary", description="")
